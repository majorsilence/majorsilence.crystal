/// <summary>
/// The pitch Crystal sets the lines of a text object at - from the top of one line to the
/// top of the next - in a report set for a printer. GdiLinePitches holds the pitch of a
/// report set for no printer, which Crystal formats for the screen; one set for a printer it
/// formats against the printer, at the printer's own font metrics, and its lines come out
/// closer together: Arial 8, 9 and 10 at 9.25, 10.2 and 11.4pt where the screen gives 10.5,
/// 11.25 and 12. A three-line 9pt Times New Roman address needs 31.65pt, not 36.
///
/// The pitch is the font's ascent, descent and external leading as GDI gives them on a
/// 600-dpi printer, for the font asked for by its em (lfHeight -size x 600/72), each turned
/// to whole twips on its own and added up. The runtime formats on whatever printer it has,
/// and every laser printer it is likely to have is 600 dpi, as is the one the references
/// are rendered with. Every pitch measured through the runtime - four-line text objects and
/// multi-line fields in Arial (5 to 36 points, all four styles), Times New Roman, Courier
/// New, Tahoma, Verdana and Calibri (6 to 18 points, Regular and Bold) - is that sum to the
/// twip.
///
/// The ascent, descent and external leading are the font's usWinAscent, usWinDescent and
/// leftover hhea line gap scaled to the em and rounded. Up to 254 pixels to the em GDI takes
/// the ascent and descent instead from the font's own per-size device metrics, which are
/// hinted and can differ by several pixels, by weight and slant: Arial Bold 8pt is 62 and
/// 16 pixels where the scaled metrics say 61 and 14, which is 0.35pt a line. Rows holds those
/// corrections for the families that have them, one letter a pixel to the em from
/// <see cref="FirstPpem"/>: 'J' none, each letter after it one pixel more, each before it
/// one fewer. Tahoma, Calibri, Cambria and Arial Black have none. Read from GDI's
/// GetTextMetrics with the Windows 11 versions of these fonts.
/// </summary>
internal static class PrinterLinePitches
{
    /// <summary>The printer resolution the pitch is taken at, in dots per inch.</summary>
    internal const int Dpi = 600;

    internal const int FirstPpem = 30;
    internal const int RowLength = 225;

    /// <summary>The line pitch in points, or null for a family the table does not hold.</summary>
    internal static double? PitchPoints(string? family, double crystalPoints, bool bold, bool italic)
    {
        if (family is null || !Metrics.TryGetValue(family, out var m))
            return null;
        int ppem = (int)Math.Round(crystalPoints * Dpi / 72, MidpointRounding.AwayFromZero);
        int ascent = Scale(m.WinAscent, ppem);
        int descent = Scale(m.WinDescent, ppem);
        int i = ppem - FirstPpem;
        if (Rows.TryGetValue(family, out var styles) && i >= 0 && i < RowLength)
        {
            var (ascentRow, descentRow) = styles[(bold ? 1 : 0) + (italic ? 2 : 0)];
            ascent += ascentRow[i] - 'J';
            descent += descentRow[i] - 'J';
        }
        int twips = Twips(ascent) + Twips(descent) + Twips(Scale(m.LineGap, ppem));
        return twips / 20.0;
    }

    private static int Scale(int units, int ppem) =>
        (int)Math.Round(units * ppem / 2048.0, MidpointRounding.AwayFromZero);

    private static int Twips(int pixels) =>
        (int)Math.Round(pixels * 1440.0 / Dpi, MidpointRounding.AwayFromZero);

