/// <summary>
/// The em size GDI gives a font asked for by its cell height, where that differs from the
/// font's cell-to-em ratio - see RdlConverter.EmPointsFor.
///
/// Crystal asks GDI for a font by cell height (a positive lfHeight) at 1440 units to the
/// inch, one twip to the device unit, and its PDF export writes the em of the font GDI
/// hands back: tmHeight - tmInternalLeading, in twips. For most sizes that is the cell
/// times upem/(usWinAscent + usWinDescent), rounded to a whole twip. Below about 15pt it
/// often is not, because there GDI sizes a TrueType font from the font's own per-size
/// device metrics rather than by scaling, and those are rounded and hinted per size, by
/// weight and slant. Arial Bold at 11pt is the case that showed it: the ratio gives
/// 197 twips (9.85pt), and GDI - and Crystal's "9.65 Tf" - give 193. Verdana Bold at 12pt
/// is 199 against 197.5; Courier New at 10pt is 187 against 177.
///
/// Each row is one family and style, one letter per twip of cell height from
/// <see cref="FirstCellTwips"/> (2pt) up, each line 70 twips (3.5pt) of it. The letter is
/// the correction to the ratio's answer: 'J' none, each letter after it one twip more,
/// each before it one twip fewer. Above the table GDI agrees with the ratio to within a
/// twip; below it, too small to matter. A family with one row has the same metrics in
/// every style. Cambria agrees with its ratio everywhere and is not listed.
///
/// Read from GDI's GetTextMetrics with the Windows 11 versions of these fonts;
/// GdiEmSizesTests compares the table against GDI wherever it runs on Windows.
/// </summary>
