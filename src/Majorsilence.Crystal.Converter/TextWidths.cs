/// <summary>
/// The width of a line of text as the engine sets it: the sum of its characters' advance
/// widths in the font, scaled from the font's em to the size it is drawn at, which is how
/// the engine's PDF writer measures a line where it breaks one. No kerning is applied, as
/// the engine applies none.
///
/// The widths are in the tables below, so a report converts the same on every machine
/// whatever fonts it has installed. Null for a family the tables do not hold, or for a line
/// with a character outside them.
/// </summary>
internal static class TextWidths
{
    internal static double? Points(string? family, double points, bool bold, bool italic, string text)
    {
        if (family is null || points <= 0 || !Advances.TryGetValue(family, out var styles))
            return null;
        // A style the family has no face for takes the nearest it has: Tahoma's italic its
        // upright, Arial Black's bold its one weight.
        var widths = styles[(bold ? 1 : 0) + (italic ? 2 : 0)] ?? styles[bold ? 1 : 0] ?? styles[0];
        if (widths is null)
            return null;
        long units = 0;
        foreach (char c in text)
        {
            int i = Index(c);
            if (i < 0 || widths[i] == 0)
                return null;
            units += widths[i];
        }
        return units * points / UnitsPerEm;
    }

    // A character's place in a table: Windows-1252's characters from the space to y with
    // diaeresis, in code page order; -1 for any other.
    private static int Index(char c)
    {
        if (c is >= ' ' and <= '~' or >= '\u00A0' and <= '\u00FF')
            return c - ' ';
        int high = c == '\0' ? -1 : Cp1252High.IndexOf(c);
        return high < 0 ? -1 : 0x80 - ' ' + high;
    }

